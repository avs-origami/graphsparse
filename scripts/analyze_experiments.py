#!/usr/bin/env python3
"""
Compare no_prune / random / learned pruning arms from a run of
`run_experiments.sh`.

Usage:
    python3 analyze_experiments.py results/experiment_20260730_120000

Reads:
    <expt_dir>/eval_{no_prune,random,learned}.log

Parses each `EVAL_STATS coverage=... greg=... moves=... dist=... tree=...`
line the trainer emits at episode boundaries. Prints per-arm mean±std for
each metric and pairwise Welch t-stats between arms.

If `--csv` is passed, also writes <expt_dir>/summary.csv with one row per
(arm, episode).

Originally generated by Claude Code Opus 4.7 xHigh, then verified and
modified by the authors.
"""

from __future__ import annotations

import math
import re
import sys
from pathlib import Path

ARMS = ["no_prune", "random", "learned"]
METRICS = ["coverage", "greg", "moves", "dist", "tree"]

STAT_RE = re.compile(
    r"EVAL_STATS\s+"
    r"coverage=([\d.eE+-]+)"
    r"(?:\s+initial_coverage=([\d.eE+-]+))?"
    r"\s+greg=(\d+)\s+"
    r"moves=(\d+)\s+"
    r"dist=([\d.eE+-]+)\s+"
    r"tree=(\d+)"
)


def parse_log(path: Path) -> list[dict[str, float]]:
    rows: list[dict[str, float]] = []
    if not path.exists():
        return rows
    for line in path.read_text().splitlines():
        m = STAT_RE.search(line)
        if not m:
            continue
        # Subtract the starting-FOV area (added to EVAL_STATS on 2026-08-10)
        # so `coverage` is exploration *gain*, not total painted pixels.
        # Missing on older logs → subtract 0 → backward compatible.
        cov = float(m.group(1))
        init = float(m.group(2)) if m.group(2) is not None else 0.0
        rows.append({
            "coverage": cov - init,
            "greg":     float(m.group(3)),
            "moves":    float(m.group(4)),
            "dist":     float(m.group(5)),
            "tree":     float(m.group(6)),
        })
    return rows


def mean(xs: list[float]) -> float:
    return sum(xs) / len(xs) if xs else float("nan")


def stddev(xs: list[float]) -> float:
    if len(xs) < 2:
        return 0.0
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def welch_t(xs: list[float], ys: list[float]) -> float:
    """Positive t → xs > ys."""
    nx, ny = len(xs), len(ys)
    if nx < 2 or ny < 2:
        return 0.0
    mx, my = mean(xs), mean(ys)
    vx = sum((x - mx) ** 2 for x in xs) / (nx - 1)
    vy = sum((y - my) ** 2 for y in ys) / (ny - 1)
    se = math.sqrt(vx / nx + vy / ny)
    return (mx - my) / se if se > 0 else 0.0


def summarise(expt_dir: Path) -> dict[str, list[dict[str, float]]]:
    data: dict[str, list[dict[str, float]]] = {}
    for arm in ARMS:
        rows = parse_log(expt_dir / f"eval_{arm}.log")
        data[arm] = rows
        print(f"  {arm:<9}  {len(rows):>3} episodes parsed")
    return data


def print_summary(data: dict[str, list[dict[str, float]]]) -> None:
    print()
    print(f"=== per-arm summary (mean ± std) ===")
    print(f"  {'arm':<10} {'n':>3}  " + "  ".join(f"{m:>18}" for m in METRICS))
    for arm in ARMS:
        rows = data[arm]
        n = len(rows)
        if n == 0:
            print(f"  {arm:<10} {n:>3}  " + "  ".join(f"{'—':>18}" for _ in METRICS))
            continue
        cells = []
        for m in METRICS:
            vs = [r[m] for r in rows]
            cells.append(f"{mean(vs):>10.2f} ± {stddev(vs):>5.2f}")
        print(f"  {arm:<10} {n:>3}  " + "  ".join(cells))


def print_pairs(data: dict[str, list[dict[str, float]]]) -> None:
    pairs = [("no_prune", "random"),
             ("no_prune", "learned"),
             ("random",   "learned")]
    print()
    print(f"=== pairwise Welch t (positive → left > right) ===")
    print(f"  {'metric':<10}  " + "  ".join(f"{a} vs {b}" for a, b in pairs))
    for m in METRICS:
        cells = []
        for a, b in pairs:
            xs = [r[m] for r in data[a]]
            ys = [r[m] for r in data[b]]
            cells.append(f"{welch_t(xs, ys):>+9.2f}      ")
        print(f"  {m:<10}  " + "  ".join(cells))


def print_efficiency(data: dict[str, list[dict[str, float]]]) -> None:
    """Coverage-per-greg — the paper's efficiency axis."""
    print()
    print(f"=== efficiency: coverage per unit greg ===")
    print(f"  {'arm':<10} {'cov/greg':>12}  (higher = more coverage bought per regen unit)")
    for arm in ARMS:
        rows = data[arm]
        if not rows:
            continue
        ratios = [r["coverage"] / r["greg"] if r["greg"] > 0 else 0.0 for r in rows]
        print(f"  {arm:<10} {mean(ratios):>12.5f} ± {stddev(ratios):>6.5f}")


def write_csv(expt_dir: Path, data: dict[str, list[dict[str, float]]]) -> None:
    out = expt_dir / "summary.csv"
    with out.open("w") as f:
        f.write("arm,episode," + ",".join(METRICS) + "\n")
        for arm in ARMS:
            for i, r in enumerate(data[arm]):
                f.write(f"{arm},{i}," + ",".join(f"{r[m]}" for m in METRICS) + "\n")
    print(f"wrote {out}")


def main() -> None:
    args = sys.argv[1:]
    write_csv_flag = "--csv" in args
    args = [a for a in args if a != "--csv"]
    if len(args) != 1:
        sys.exit("usage: analyze_experiments.py <expt_dir> [--csv]")
    expt_dir = Path(args[0])
    if not expt_dir.is_dir():
        sys.exit(f"not a directory: {expt_dir}")

    print(f"=== {expt_dir} ===")
    data = summarise(expt_dir)
    print_summary(data)
    print_pairs(data)
    print_efficiency(data)
    if write_csv_flag:
        write_csv(expt_dir, data)


if __name__ == "__main__":
    main()
